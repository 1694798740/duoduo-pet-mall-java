-- 48 · 商品编辑 / 审核并发保护（乐观锁，2026-10-24，A-07）
--
-- 问题：内容编辑此前是「整行 updateById」（MyBatis-Plus 会把实体里所有非 null 字段全部写回），
-- 而审核是「按 id 定列更新」。两次写并发时，编辑可能把运营刚落的 REJECTED 覆盖回 APPROVED
-- （或把审核原因 / 审核来源 / 驳回计数一起冲掉），且双方都返回 200。
--
-- 方案：t_spu 增加 version，内容编辑与审核判定都以「读到的 version」为前置条件更新，
-- 更新成功 version+1；影响行数为 0 即表示期间有他人写入，返回 409 让调用方刷新重试。
--
-- 为什么版本只守内容 / 审核两条写路径：
--   上下架与改价改库存是正交的高频动作（卖家随时可做），把它们也纳入版本条件，
--   会让「运营正在审核时卖家下架」这种正常操作变成 409 噪音。
--
-- 幂等：2026-10-24 起新环境由 02 的建表语句覆盖；本脚本对已有环境执行一次。
SET NAMES utf8mb4;
USE `duoduo_product`;

ALTER TABLE t_spu
    ADD COLUMN version INT NOT NULL DEFAULT 0 COMMENT '乐观锁版本（内容编辑 / 审核判定写路径）';
