-- ============================================================================
-- E17 · 权限即时生效（permVersion）：用户库增量 DDL
-- （对已有环境执行；全新环境直接跑 01-duoduo-user.sql，两处已同步）
-- ============================================================================
-- 一句话口径：访问令牌里带一个版本号 pv，角色变更时该用户的版本 +1；
--   网关比对「令牌里的版本」与「当前版本」，不一致即 401 → 客户端刷新后拿到新角色。
--   于是「刚被撤销的权限」下一个请求就失效，既不用等 15 分钟自然过期，
--   也不必把对方踢去重新登录。
--
-- 版本口径（键名 / TTL / 缺失时放行）见 com.duoduo.common.security.perm.PermVersion；
-- 本脚本只落**权威值**这一列，感知副本在 Redis（写失败时退化为吊销刷新令牌）。
-- ============================================================================
SET NAMES utf8mb4;

USE `duoduo_user`;

-- 幂等说明：MySQL 不支持 ADD COLUMN IF NOT EXISTS，重复执行会报 1060（刻意如此，
-- 与 28-e15-license-expiry.sql 同一口径）—— 静默忽略更有害：它会让"这次到底改没改"
-- 变得无法从输出判断。
--
-- NOT NULL DEFAULT 0：
--   · 存量账号一次 ALTER 即补齐为 0，与「新注册账号从 0 开始」一致，不需要数据回填；
--   · 0 同时是 PermVersion.INITIAL，避免出现"库里是 0、代码以为从 1 开始"的分裂。
-- ---------------------------------------------------------------------------
ALTER TABLE `t_user`
    ADD COLUMN `perm_version` BIGINT NOT NULL DEFAULT 0
        COMMENT '权限版本（E17）：角色变更时 +1；访问令牌带签发时的值，网关比对不一致即 401'
        AFTER `credit_score`;

-- 不需要给本列建索引：读它一律按主键（user_id）单行取，
-- 没有「按版本区间筛选用户」这类查询 —— 加了只会多一份写放大。
