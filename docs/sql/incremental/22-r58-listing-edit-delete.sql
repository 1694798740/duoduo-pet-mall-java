SET NAMES utf8mb4;
USE `duoduo_product`;

-- ---------------------------------------------------------------------------
-- t_listing 补 deleted_at：软删标记
-- ---------------------------------------------------------------------------
-- 为什么必须软删、不能物理删（与 R56 分享圈同源的教训）：
--   ① 闲置一旦成交，就与订单、会话、举报记录产生引用关系 —— 物理删会让别人的订单页
--      与聊天记录出现「查无此物」，而用户无法理解发生了什么；
--   ② 审核与举报留痕需要「这条内容曾经存在」，删了就无从追溯。
-- 因此所有读路径一律带 deleted_at IS NULL，删除只写时间不删行。
ALTER TABLE `t_listing`
    ADD COLUMN `deleted_at` DATETIME NULL COMMENT '软删时间（UTC）；非 NULL 即已删除，所有读路径均排除' AFTER `updated_at`;

CREATE INDEX `idx_listing_deleted` ON `t_listing` (`deleted_at`);
