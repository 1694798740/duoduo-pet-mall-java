package com.duoduo.ai.support;

import java.util.List;

/**
 * 售后 / 交易政策知识库（第五十八轮 · AI 加强项 S2）。
 *
 * <h2>为什么需要它，而不是继续说「我查不到」</h2>
 * 第五十七轮为了防编造，把物流 / 退换 / 运费 / 券 / 支付这五类问题一律引到
 * 「我查不到，你去某某页看」。那比让模型瞎编安全得多，但代价是：
 * 用户问「怎么退货」得到的答案是「我不知道」—— 而这个问题<b>有确定答案</b>，
 * 答案就写在系统的流程里（未发货可直接退、已发货走售后、签收后走仲裁）。
 * 「不知道」说多了，导购就成了摆设。
 *
 * <h2>知识库里放什么：流程与入口，不放承诺
 * 每条回答只陈述**系统真实的流程顺序**与**去哪儿操作**，绝不涉及
 * 时效（几天到账）、赔付比例、是否包邮这类**随配置 / 随订单变化**的数字 ——
 * 那些数字一旦写死在提示词里，改了配置也不会跟着变，属于另一种编造。
 * 凡是有具体数字的，一律写「以页面显示为准」并给出入口。
 *
 * <h2>维护纪律
 * 每条目必须可追溯到代码里的真实流程；流程改了这里必须同步。
 * 因此条目刻意写得**像流程说明**（先做什么、再做什么），
 * 而不是像营销文案 —— 后者改起来没人知道该问谁。
 */
public final class PolicyKnowledge {

    /**
     * 政策条目。
     *
     * @param keywords 命中词（任意一个出现即命中）
     * @param answer   回答（流程 + 入口，不含时效承诺）
     */
    private record Policy(List<String> keywords, String answer) {
    }

    /**
     * 条目顺序 = 匹配优先级：**更具体的排在前面**。
     * 「卖家不同意退款怎么办」同时含「退款」与「卖家不同意」，若退货条目在先，
     * 用户拿到的是退货流程而不是他要的仲裁入口 —— 顺序错了表现为「答得不算错但没用」。
     */
    private static final List<Policy> POLICIES = List.of(
            new Policy(
                    List.of("售后", "仲裁", "卖家不同意", "驳回", "申诉"),
                    "售后被驳回或卖家超时未处理时，可以在售后详情里申请平台介入（仲裁），"
                            + "由运营按双方凭证裁定。申请前把照片 / 聊天记录留好，裁定主要看这些。"),
            new Policy(
                    List.of("退货", "退款", "换货", "怎么退", "能退吗", "不想要了", "退掉"),
                    "退货分三种情况，按顺序对号入座："
                            + "① 还没发货 —— 在「我的 → 我的订单」里直接退款，钱原路退回，卖家不再发货；"
                            + "② 已发货 —— 对那一单发起售后，卖家同意后你按提示寄回，**卖家签收后**退款才会到账；"
                            + "③ 已确认收货（钱已给卖家）—— 仍可发起售后，由平台按规则裁定。"
                            + "每一步在订单详情页都有对应按钮，进度以页面显示为准。"),
            new Policy(
                    List.of("物流", "快递", "发货了", "到哪了", "什么时候到", "签收", "运单", "几天到"),
                    "物流进度在「我的 → 我的订单 → 订单详情」里能看到完整轨迹（发货后每一站都会更新）。"
                            + "具体时效取决于快递公司和你所在的地区，我这边看不到你的订单，不敢替它报天数 —— 以页面显示为准。"),
            new Policy(
                    List.of("评价", "追评", "打分"),
                    "确认收货后可以评价；追评要在评价后一段时间内完成，能不能追以订单页的按钮为准"
                            + "（按钮不可点就是过了期限）。"),
            new Policy(
                    List.of("信用分", "信用"),
                    "信用分由平台按履约情况（完成率、评价、售后结果）自动计算，在「我的 → 我的信用」里能看到明细，"
                            + "不支持手动修改。")
    );

    private PolicyKnowledge() {
    }

    /** 命中政策条目则返回回答，否则 {@code null}（交给后续的「答不了」出口处理） */
    public static String answerFor(String message) {
        String text = message == null ? "" : message;
        if (text.isBlank()) {
            return null;
        }
        for (Policy policy : POLICIES) {
            for (String keyword : policy.keywords()) {
                if (text.contains(keyword)) {
                    return policy.answer();
                }
            }
        }
        return null;
    }

    /** 条目数（供测试断言「知识库不是空的」） */
    public static int size() {
        return POLICIES.size();
    }
}
